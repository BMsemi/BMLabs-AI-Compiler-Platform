"""Generic synthesis and formal RTL/netlist equivalence; no fabric binding."""
from pathlib import Path
import json
from django.conf import settings
from .execution import wsl_command, wsl_path


def tool_command(name, arguments, work=None, timeout=180):
    path = settings.TOOLCHAIN.get(name + '_PATH', '')
    if not path and name == 'ABC' and settings.TOOLCHAIN.get('YOSYS_PATH'):
        yosys = settings.TOOLCHAIN['YOSYS_PATH'].replace('\\', '/')
        path = yosys.rsplit('/', 1)[0] + '/yosys-abc' + ('.exe' if yosys.endswith('.exe') else '')
    if not path and name in ('IVERILOG', 'VVP'):
        path = '/usr/bin/' + name.lower()
    if not path:
        raise ValueError(f'{name}_PATH is not configured')
    if path.startswith('/'):
        argv = wsl_command(settings.COMPILER_WSL_DISTRO, [path, *arguments], timeout=timeout)
        if work:
            argv[3:3] = ['--cd', wsl_path(work)]
        return argv
    return [path, *arguments]


def prepare_scripts(work):
    # Fixed filenames, generated by the trusted pipeline, not user command text.
    synthesis = '''read_verilog model.v
hierarchy -check -top linear_model
synth -noabc -top linear_model
abc -script "+strash;map"
clean
check -assert
tee -o synthesis_stats.json stat -json
write_json synthesized.json
write_verilog -noattr synthesized.v
'''
    (work/'synthesis.ys').write_text(synthesis, encoding='utf-8')
    # Compare observable ports. Optimized-away internal debug wires may legally
    # become X in the netlist and must not be treated as behavioral outputs.
    for name in ('model', 'synthesized'):
        # Use the tool's own mapped cells directly; re-synthesizing its emitted
        # Verilog expands those cells and makes large proof preparation costly.
        frontend = ('read_verilog model.v\nsynth -noabc -top linear_model\n' if name == 'model'
                    else 'read_json synthesized.json\nhierarchy -check -top linear_model\n')
        script = (frontend + 'flatten\n'
                  f'aigmap\nwrite_aiger -symbols -map {name}.map {name}.aig\n'
                  f'blackbox\nwrite_json {name}_interface.json\n')
        (work/(name+'_aig.ys')).write_text(script, encoding='utf-8')


def run_synthesis(work, command):
    prepare_scripts(work)
    command('yosys_synthesis', tool_command('YOSYS', ['-s', 'synthesis.ys'], work), 210)
    for name in ('synthesized.v', 'synthesized.json', 'synthesis_stats.json'):
        if not (work/name).is_file() or not (work/name).stat().st_size:
            raise ValueError(f'Yosys did not produce {name}')
    verify_equivalence(work, command)
    command('netlist_compile', tool_command('IVERILOG',
        ['-g2012', '-s', 'tb', '-o', 'netlist.vvp', 'synthesized.v', 'tb.v'], work), 90)
    # Dense 32x32 gate-level designs execute the complete 391-vector suite;
    # the measured reference run takes ~264 s on the configured native runtime.
    result = command('netlist_simulation', tool_command('VVP', ['netlist.vvp'], work, timeout=360), 360)
    return result


def verify_equivalence(work, command):
    for name in ('model', 'synthesized'):
        command(name+'_aig', tool_command('YOSYS', ['-s', name+'_aig.ys'], work, timeout=240), 240)
    contracts = []
    for name in ('model', 'synthesized'):
        # Export the executable AIG before blackboxing a copy in the Yosys process.
        # The small JSON retains every port without parsing hundreds of MB of cells.
        ports = json.loads((work/(name+'_interface.json')).read_text())['modules']['linear_model']['ports']
        # AIGER sorts port names and preserves bit order; map files omit constant
        # output bits, so validate complete JSON port declarations and headers.
        contract = [(n, p['direction'], len(p['bits']), p.get('offset', 0), p.get('upto', 0)) for n, p in sorted(ports.items())]
        with (work/(name+'.aig')).open('rb') as stream:
            header = stream.readline().decode('ascii').split()
        counts = [sum(p[2] for p in contract if p[1] == direction) for direction in ('input', 'output')]
        if header[0] != 'aig' or [int(header[2]), int(header[4])] != counts or int(header[3]) != 0 or not counts[1]:
            raise ValueError('AIG interface mismatch or unexpected sequential state.')
        contracts.append(contract)
    if contracts[0] != contracts[1]:
        raise ValueError('AIG port declarations differ; refusing an ambiguous equivalence comparison.')
    proof = command('abc_equivalence', tool_command('ABC', ['-s', '-c', 'cec model.aig synthesized.aig'], work), 210)
    if not any(line.startswith('Networks are equivalent.') for line in proof['stdout'].splitlines()):
        raise ValueError('ABC did not prove output equivalence (zero exit alone is insufficient).')
